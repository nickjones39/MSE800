"""Repository layer.

Each entity gets a small repository that knows how to persist and query it. A
shared base class provides the generic ``INSERT`` logic, and each subclass
declares its table name and column order (which must match the corresponding
dataclass field order in :mod:`models`).

``rate_id`` and ``transaction_id`` are ``SERIAL`` columns generated by the
database, so they are omitted from the ``INSERT`` column lists. The transaction
repository returns plain dictionaries (not dataclasses) because it enriches the
rows with the generated ``transaction_id`` and the customer's name for display.
"""

from __future__ import annotations

from dataclasses import astuple
from typing import Sequence, TypeVar

import psycopg
from psycopg.rows import dict_row

from .models import Currency, Customer, ExchangeRate

T = TypeVar("T")


class Repository:
    """Generic repository: inserts one dataclass row into a table."""

    table: str = ""
    columns: tuple[str, ...] = ()

    def __init__(self, connection: psycopg.Connection) -> None:
        self._connection = connection

    def insert(self, record: T) -> None:
        values = astuple(record)
        placeholders = ", ".join(["%s"] * len(self.columns))
        sql = (
            f"INSERT INTO {self.table} ({', '.join(self.columns)}) "
            f"VALUES ({placeholders})"
        )
        self._connection.execute(sql, values)

    def insert_many(self, records: Sequence[T]) -> None:
        for record in records:
            self.insert(record)


class CustomerRepository(Repository):
    table = "customer"
    columns = ("customer_id", "first_name", "last_name", "email", "phone")

    def find_all(self) -> list[Customer]:
        with self._connection.cursor(row_factory=dict_row) as cursor:
            cursor.execute(
                "SELECT customer_id, first_name, last_name, email, phone "
                "FROM customer ORDER BY customer_id"
            )
            return [Customer(**row) for row in cursor.fetchall()]

    def exists(self, customer_id: str) -> bool:
        with self._connection.cursor() as cursor:
            cursor.execute(
                "SELECT 1 FROM customer WHERE customer_id = %s", (customer_id,)
            )
            return cursor.fetchone() is not None

    def count(self) -> int:
        with self._connection.cursor() as cursor:
            cursor.execute("SELECT COUNT(*) FROM customer")
            return cursor.fetchone()[0]


