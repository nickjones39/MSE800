class ExchangeRateRepository(Repository):
    table = "exchange_rate"
    columns = ("base_currency", "quote_currency", "rate", "effective_date")

    def find_all(self) -> list[ExchangeRate]:
        with self._connection.cursor(row_factory=dict_row) as cursor:
            cursor.execute(
                "SELECT base_currency, quote_currency, rate, effective_date "
                "FROM exchange_rate "
                "ORDER BY base_currency, quote_currency, effective_date"
            )
            return [ExchangeRate(**row) for row in cursor.fetchall()]

    def find_latest(
        self, base_currency: str, quote_currency: str
    ) -> ExchangeRate | None:
        """Return the most recent rate for a currency pair, or ``None``."""
        with self._connection.cursor(row_factory=dict_row) as cursor:
            cursor.execute(
                "SELECT base_currency, quote_currency, rate, effective_date "
                "FROM exchange_rate "
                "WHERE base_currency = %s AND quote_currency = %s "
                "ORDER BY effective_date DESC LIMIT 1",
                (base_currency, quote_currency),
            )
            row = cursor.fetchone()
            return ExchangeRate(**row) if row else None

    def count(self) -> int:
        with self._connection.cursor() as cursor:
            cursor.execute("SELECT COUNT(*) FROM exchange_rate")
            return cursor.fetchone()[0]


class TransactionRepository(Repository):
    table = "exchange_transaction"
    columns = (
        "customer_id",
        "base_currency",
        "quote_currency",
        "amount_base",
        "amount_quote",
        "rate_used",
        "transaction_date",
    )

    def find_all(self) -> list[dict]:
        """Return transactions enriched with the customer's full name."""
        with self._connection.cursor(row_factory=dict_row) as cursor:
            cursor.execute(
                "SELECT t.transaction_id, c.first_name, c.last_name, "
                "t.base_currency, t.quote_currency, t.amount_base, "
                "t.amount_quote, t.rate_used, t.transaction_date "
                "FROM exchange_transaction AS t "
                "JOIN customer AS c ON c.customer_id = t.customer_id "
                "ORDER BY t.transaction_id"
            )
            return cursor.fetchall()

    def count(self) -> int:
        with self._connection.cursor() as cursor:
            cursor.execute("SELECT COUNT(*) FROM exchange_transaction")
            return cursor.fetchone()[0]
